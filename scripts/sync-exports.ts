// Regenerates the `exports` map of packages/frontend-sdk/package.json: one entry per implemented
// subpath (src/<name>/index.ts exists) plus the throwing root "." (design doc §C1 "Build"), and the
// SDK facts @platform/webpack-preset and @platform/eslint-plugin build on (src/generated/sdk.ts in
// each: the subpaths and the share range). `--check` fails instead of writing when anything is stale.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { REPO_ROOT, SDK_DIR, implementedSubpaths } from './lib/subpaths.ts';

export type ExportsMap = Record<string, string | { types: string; import: string }>;

export function buildExportsMap(subpaths: readonly string[]): ExportsMap {
  const map: ExportsMap = { '.': { types: './dist/root.d.ts', import: './dist/root.js' } };
  for (const name of subpaths) {
    map[`./${name}`] = { types: `./dist/${name}/index.d.ts`, import: `./dist/${name}/index.js` };
  }
  map['./package.json'] = './package.json';
  return map;
}

/** The range shells and remotes share the SDK under: `^<major>.0.0-0`, which also accepts that major's pre-releases (§C3 "Versioning"). */
export function shareRange(version: string): string {
  const major = /^(\d+)\./.exec(version)?.[1];
  if (!major) throw new Error(`SDK version ${version} is not SemVer`);
  return `^${major}.0.0-0`;
}

export function buildToolingConstants(subpaths: readonly string[], sdkVersion: string): string {
  return [
    '// Generated by scripts/sync-exports.ts from packages/frontend-sdk (subpaths.json, package.json). Do not edit; run `pnpm exports:sync`.',
    '',
    "export const SDK_PACKAGE = '@platform/frontend-sdk';",
    '',
    '/** The SDK subpaths a consumer may import (the exports map, without the throwing root). */',
    `export const SDK_SUBPATHS = ${JSON.stringify(subpaths)} as const;`,
    '',
    '/** The range every shell and remote shares the SDK under. */',
    `export const SDK_SHARE_RANGE = '${shareRange(sdkVersion)}';`,
    '',
  ].join('\n');
}

const TOOLING = ['packages/webpack-preset/src/generated/sdk.ts', 'packages/eslint-plugin/src/generated/sdk.ts'];

function main(): void {
  const check = process.argv.includes('--check');
  const file = join(SDK_DIR, 'package.json');
  const text = readFileSync(file, 'utf8');
  const pkg = JSON.parse(text) as { exports?: ExportsMap };
  const subpaths = implementedSubpaths();
  const want = buildExportsMap(subpaths);
  const stale: string[] = [];
  if (JSON.stringify(pkg.exports) !== JSON.stringify(want)) {
    if (check) stale.push('packages/frontend-sdk/package.json exports');
    else {
      pkg.exports = want;
      writeFileSync(file, `${JSON.stringify(pkg, null, 2)}\n`);
      console.log(`exports map updated (${Object.keys(want).length - 2} subpaths)`);
    }
  }
  const constants = buildToolingConstants(subpaths, (pkg as { version: string }).version);
  for (const rel of TOOLING) {
    const path = join(REPO_ROOT, rel);
    if (existsSync(path) && readFileSync(path, 'utf8') === constants) continue;
    if (check) stale.push(rel);
    else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, constants);
      console.log(`updated ${rel}`);
    }
  }
  if (stale.length > 0) {
    console.error(`Stale: ${stale.join(', ')}. Run \`pnpm exports:sync\`.`);
    process.exit(1);
  }
}

if (import.meta.url === `file://${process.argv[1]}`) main();
